-- Consumo diario de servicios públicos (gas, agua edificio, agua
-- producción), tomado a mano del macromedidor cada día (hoja MAN-F-001).
-- Antes vivía solo en un Excel (Control.xlsx); acá se captura y se arma el
-- resumen mensual en Estadísticas.
--
-- lectura_m3 es lo que marca el medidor ese día; consumo_m3 es la resta
-- contra la lectura anterior de ese mismo medidor (se calcula en la app al
-- capturar, no acá, porque hay huecos: un medidor puede no tener lectura
-- varios días seguidos y el próximo consumo se calcula contra la última
-- lectura real, no contra el día anterior).
create table consumos_servicios (
  id uuid primary key default gen_random_uuid(),
  fecha date not null unique,
  gas_lectura_m3 numeric(14, 2),
  gas_consumo_m3 numeric(14, 2),
  agua_edificio_lectura_m3 numeric(14, 2),
  agua_edificio_consumo_m3 numeric(14, 2),
  agua_produccion_lectura_m3 numeric(14, 2),
  agua_produccion_consumo_m3 numeric(14, 2),
  -- true cuando la lectura no se tomó directo del medidor (sin hoja de
  -- inspección, dato inconsistente anotado, etc.) y se completó a mano.
  estimado boolean not null default false,
  observaciones text,
  created_by uuid references profiles(id),
  created_at timestamptz not null default now()
);

alter table consumos_servicios enable row level security;
create policy "consumos_servicios_select" on consumos_servicios
  for select to authenticated
  using (is_staff() or current_role_is('asistente_adm') or current_role_is('planeacion'));
create policy "consumos_servicios_insert" on consumos_servicios
  for insert to authenticated with check (is_staff());
create policy "consumos_servicios_update" on consumos_servicios
  for update to authenticated using (is_staff());
create policy "consumos_servicios_delete" on consumos_servicios
  for delete to authenticated using (current_role_is('jefe_planta'));

create index idx_consumos_servicios_fecha on consumos_servicios(fecha);

